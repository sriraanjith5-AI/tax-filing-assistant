"""
Shared evidence-extraction and text-matching helpers used by both
RAGEvaluator (evaluation/rag_evaluator.py) and RetrievalMetrics
(evaluation/retrieval_metrics.py) to determine whether a retrieved
chunk actually contains a golden-dataset evidence passage.

Matching is intentionally based on normalized substring containment
rather than chunk_id, since chunk_id is generated by the current
chunking strategy and may change when chunking changes; the golden
dataset's evidence text is stable across chunking/retriever changes.
"""

import re
from difflib import SequenceMatcher


# Fraction of the (normalized) evidence text's length that must
# appear as one contiguous run inside a chunk for the chunk to count
# as a match, once exact whole-string containment fails. Evidence
# passages sometimes span a chunk boundary (a 700-char chunk can
# start mid-sentence), so a chunk can legitimately contain most - but
# not all - of the evidence text. 0.6 was chosen so a chunk missing
# a short lead-in/trailing clause still counts, while two chunks that
# only share a few common words do not.
PARTIAL_MATCH_COVERAGE = 0.6


def extract_evidence_items(retrieval_ground_truth):
    """
    Extract evidence items from retrieval ground truth.

    Supports:

    {"evidence": "evidence text"}
    {"evidence": ["evidence text 1", "evidence text 2"]}
    {"evidence": [{"text": "...", "page": 12}, ...]}
    """

    if not retrieval_ground_truth:
        return []

    evidence = retrieval_ground_truth.get("evidence", [])

    if isinstance(evidence, str):
        evidence = [evidence]

    if not isinstance(evidence, list):
        return []

    evidence_items = []

    for item in evidence:

        if isinstance(item, str):

            text = item.strip()

            if text:
                evidence_items.append(
                    {
                        "text": text,
                        "source": retrieval_ground_truth.get(
                            "source_section"
                        ),
                        "page": retrieval_ground_truth.get(
                            "source_page"
                        ),
                    }
                )

        elif isinstance(item, dict):

            text = item.get("text")

            if not text:
                continue

            evidence_items.append(
                {
                    "text": text.strip(),
                    "source": item.get("source"),
                    "page": item.get("page"),
                }
            )

    return evidence_items


def find_matching_evidence(chunk_content, evidence_items):
    """
    Returns the indexes of evidence_items whose (normalized) text is
    considered present in chunk_content.

    Two-tier match:

    1. Exact: normalized_evidence is a substring of normalized_chunk.
       Cheap, and the common case when the evidence passage lands
       fully inside one chunk.

    2. Partial: falls back to word-level diffing (via difflib) and
       sums every matching run of words shared between chunk and
       evidence. If that total covers >= PARTIAL_MATCH_COVERAGE of
       the evidence's word count, the chunk still counts as a match.
       This handles evidence passages that straddle a chunk boundary
       - e.g. a 700-char chunk starting mid-sentence, so it contains
       the back 80% of the evidence sentence but not the opening
       clause - or that have an unrelated aside spliced in the
       middle by the chunker, which would otherwise split one
       semantic match into two smaller runs.

       Matching is done on WORDS, not characters: SequenceMatcher's
       autojunk heuristic kicks in on sequences of 200+ elements and
       silently drops frequently-repeated elements as "popular",
       which corrupts character-level matching on typical evidence
       sentences (~200-300 chars) - words rarely hit that count and
       are the more meaningful unit here anyway.
    """

    normalized_chunk = normalize_text(chunk_content)
    chunk_words = normalized_chunk.split()

    matched_indexes = []

    for index, evidence_item in enumerate(evidence_items):

        normalized_evidence = normalize_text(
            evidence_item.get("text", "")
        )

        if not normalized_evidence:
            continue

        if normalized_evidence in normalized_chunk:
            matched_indexes.append(index)
            continue

        evidence_words = normalized_evidence.split()

        if not evidence_words:
            continue

        matcher = SequenceMatcher(
            None, chunk_words, evidence_words, autojunk=False
        )

        matched_word_count = sum(
            block.size for block in matcher.get_matching_blocks()
        )

        coverage = matched_word_count / len(evidence_words)

        if coverage >= PARTIAL_MATCH_COVERAGE:
            matched_indexes.append(index)

    return matched_indexes


def normalize_text(text):
    """
    Lowercase + collapse whitespace, so matching ignores case,
    multiple spaces, newlines and tabs.

    Also undoes two PDF-text-extraction artifacts that otherwise
    break substring matching even when a chunk clearly contains the
    evidence passage:

    - Line-wrap hyphenation: "includ- ing" -> "including" (a word
      split across a line break by pdfplumber/pypdf, with the
      hyphen and the line's trailing space both still present).
    - Stray spaces before punctuation: "P .L. 119 -21" -> "P.L.
      119-21" (extraction sometimes inserts a space before a period
      or hyphen that isn't there in the source).

    Without this, a chunk that visibly contains the evidence text
    (to a human reading it) fails exact substring matching purely
    because of how the PDF extractor tokenized whitespace - see
    evaluation/results/retrieval_metrics_*.csv before this fix,
    where every question scored 0 despite ragas' LLM judge scoring
    the same retrieved chunks as highly relevant.
    """

    if not text:
        return ""

    normalized = text.lower()

    # "includ- ing" -> "including"
    normalized = re.sub(r"(\w)-\s+(\w)", r"\1\2", normalized)

    # "P .L." -> "P.L.", "119 -21" -> "119-21"
    normalized = re.sub(r"\s+([.\-,;:])", r"\1", normalized)

    return " ".join(normalized.split())
