from evaluation.evaluation_dataclass import EvaluationResult


class RAGEvaluator:
    """
    Evaluates retrieval results against stable retrieval ground truth.

    The evaluator intentionally does NOT depend on chunk_id because
    chunk_id is generated by the current chunking strategy and may
    change when the chunking implementation changes.

    Retrieval ground truth contains stable evidence text and optionally
    source/page information.

    Metrics calculated:

    - Hit@K
    - Recall@K
    - MRR
    """

    def evaluate_retrieval(
        self,
        question_id,
        query,
        expected_answer,
        retrieved_results,
        retrieval_ground_truth,
        k=3,
    ):
        """
        Evaluate retrieval results.

        Parameters
        ----------
        question_id : str
            Golden dataset question ID.

        query : str
            User query.

        expected_answer : str
            Expected answer from the golden dataset.

        retrieved_results : list
            Results returned by VectorRetriever.

        retrieval_ground_truth : dict
            Stable evidence used to determine whether retrieved chunks
            are relevant.

        k : int
            Number of top retrieval results considered for Hit@K,
            Recall@K and MRR.

        Returns
        -------
        EvaluationResult
        """

        retrieved_count = len(retrieved_results)

        # ========================================================
        # 1. EMPTY RETRIEVAL
        # ========================================================

        if retrieved_count == 0:

            return EvaluationResult(
                question_id=question_id,
                query=query,
                expected_answer=expected_answer,
                actual_answer="",
                retrieved_count=0,
                top_score=0.0,
                retrieval_success=False,
                answer_score=0.0,
                evaluation_status="RETRIEVAL_FAILED",
                hit_at_k=0.0,
                recall_at_k=0.0,
                reciprocal_rank=0.0,
            )

        # ========================================================
        # 2. TOP SCORE
        # ========================================================

        top_score = retrieved_results[0].score

        # ========================================================
        # 3. EXTRACT GROUND-TRUTH EVIDENCE
        # ========================================================

        evidence_items = self._extract_evidence_items(
            retrieval_ground_truth
        )

        # ========================================================
        # 4. EMPTY GROUND TRUTH
        # ========================================================

        if not evidence_items:

            return EvaluationResult(
                question_id=question_id,
                query=query,
                expected_answer=expected_answer,
                actual_answer="",
                retrieved_count=retrieved_count,
                top_score=top_score,
                retrieval_success=False,
                answer_score=0.0,
                evaluation_status="GROUND_TRUTH_INVALID",
                hit_at_k=0.0,
                recall_at_k=0.0,
                reciprocal_rank=0.0,
            )

        # ========================================================
        # 5. CONSIDER ONLY TOP K RESULTS
        # ========================================================

        top_k_results = retrieved_results[:k]

        # ========================================================
        # 6. DETERMINE WHICH EVIDENCE ITEMS WERE RETRIEVED
        # ========================================================

        retrieved_evidence_indexes = set()

        first_relevant_rank = None

        for rank, retrieved_result in enumerate(
            top_k_results,
            start=1,
        ):

            document = retrieved_result.document

            if document is None:
                continue

            chunk_content = document.page_content

            # ----------------------------------------------------
            # Check this retrieved chunk against every evidence
            # item.
            # ----------------------------------------------------

            matched_indexes = self._find_matching_evidence(
                chunk_content=chunk_content,
                evidence_items=evidence_items,
            )

            if matched_indexes:

                retrieved_evidence_indexes.update(
                    matched_indexes
                )

                # MRR uses the FIRST relevant retrieved result.
                if first_relevant_rank is None:

                    first_relevant_rank = rank

        # ========================================================
        # 7. HIT@K
        # ========================================================

        hit_at_k = (
            1.0
            if len(retrieved_evidence_indexes) > 0
            else 0.0
        )

        # ========================================================
        # 8. RECALL@K
        # ========================================================

        total_evidence_items = len(evidence_items)

        recall_at_k = (
            len(retrieved_evidence_indexes)
            / total_evidence_items
        )

        # ========================================================
        # 9. MRR
        # ========================================================

        if first_relevant_rank is None:

            reciprocal_rank = 0.0

        else:

            reciprocal_rank = 1.0 / first_relevant_rank

        # ========================================================
        # 10. RETRIEVAL SUCCESS
        # ========================================================

        retrieval_success = hit_at_k > 0

        # ========================================================
        # 11. STATUS
        # ========================================================

        if retrieval_success:

            evaluation_status = "RETRIEVAL_SUCCESS"

        else:

            evaluation_status = "RETRIEVAL_FAILED"

        # ========================================================
        # 12. RETURN RESULT
        # ========================================================

        return EvaluationResult(
            question_id=question_id,
            query=query,
            expected_answer=expected_answer,
            actual_answer="",
            retrieved_count=retrieved_count,
            top_score=top_score,
            retrieval_success=retrieval_success,
            answer_score=0.0,
            evaluation_status=evaluation_status,
            hit_at_k=hit_at_k,
            recall_at_k=recall_at_k,
            reciprocal_rank=reciprocal_rank,
        )

    # ============================================================
    # PRIVATE METHODS
    # ============================================================

    def _extract_evidence_items(
        self,
        retrieval_ground_truth,
    ):
        """
        Extract evidence items from retrieval ground truth.

        Supported structure:

        {
            "evidence": [
                {
                    "text": "...",
                    "page": 12
                },
                {
                    "text": "...",
                    "page": 13
                }
            ]
        }

        Also supports:

        {
            "evidence": [
                "evidence text 1",
                "evidence text 2"
            ]
        }
        """

        if not retrieval_ground_truth:
            return []

        evidence = retrieval_ground_truth.get(
            "evidence",
            []
        )

        if not isinstance(evidence, list):
            return []

        evidence_items = []

        for item in evidence:

            # ----------------------------------------------------
            # Evidence stored as string
            # ----------------------------------------------------

            if isinstance(item, str):

                text = item.strip()

                if text:
                    evidence_items.append(
                        {
                            "text": text,
                        }
                    )

            # ----------------------------------------------------
            # Evidence stored as object
            # ----------------------------------------------------

            elif isinstance(item, dict):

                text = item.get("text")

                if not text:
                    continue

                evidence_items.append(
                    {
                        "text": text.strip(),
                        "source": item.get("source"),
                        "page": item.get("page"),
                    }
                )

        return evidence_items

    def _find_matching_evidence(
        self,
        chunk_content,
        evidence_items,
    ):
        """
        Determine which evidence items are present in a chunk.

        Matching is intentionally based on normalized text rather
        than chunk_id.

        A match is considered successful when the normalized
        evidence text occurs inside the normalized chunk.

        This works when the evidence passage is fully contained
        within a retrieved chunk.
        """

        normalized_chunk = self._normalize_text(
            chunk_content
        )

        matched_indexes = []

        for index, evidence_item in enumerate(
            evidence_items
        ):

            evidence_text = evidence_item.get(
                "text",
                ""
            )

            normalized_evidence = self._normalize_text(
                evidence_text
            )

            if not normalized_evidence:
                continue

            if normalized_evidence in normalized_chunk:

                matched_indexes.append(index)

        return matched_indexes

    @staticmethod
    def _normalize_text(text):
        """
        Normalize text so matching is not affected by:

        - Case
        - Multiple spaces
        - Newlines
        - Tabs
        """

        if not text:
            return ""

        return " ".join(
            text.lower().split()
        )